"""In-memory thread-safe process tree and event storage registry."""

from __future__ import annotations

import contextlib
import logging
import threading
from collections import deque
from dataclasses import dataclass, field
from datetime import datetime
from enum import StrEnum
from typing import Any

from src.features import parse_ts

logger = logging.getLogger("orchestrator.registry")


class ProcessStatus(StrEnum):
    ACTIVE = "ACTIVE"
    EVALUATED_BENIGN = "EVALUATED_BENIGN"
    MALICIOUS = "MALICIOUS"
    KILLED = "KILLED"
    STOPPED = "STOPPED"


@dataclass
class ProcessRecord:
    pid: int
    ppid: int = 0
    image_file_name: str = ""
    start_time: datetime | None = None
    stop_time: datetime | None = None
    exit_code: int | None = None
    status: ProcessStatus = ProcessStatus.ACTIVE
    children: set[int] = field(default_factory=set)
    events: list[dict[str, Any]] = field(default_factory=list)
    evaluated_horizons: set[float] = field(default_factory=set)
    last_event_time: datetime | None = None

    @property
    def is_alive(self) -> bool:
        return self.status not in (ProcessStatus.KILLED, ProcessStatus.STOPPED)


class ProcessRegistry:
    """Thread-safe registry for active and recently terminated processes."""

    def __init__(self, max_events_per_proc: int = 50_000) -> None:
        self._lock = threading.RLock()
        self._processes: dict[int, ProcessRecord] = {}
        self._max_events_per_proc = max_events_per_proc

    def get(self, pid: int) -> ProcessRecord | None:
        with self._lock:
            return self._processes.get(pid)

    def get_or_create(self, pid: int) -> ProcessRecord:
        with self._lock:
            if pid not in self._processes:
                self._processes[pid] = ProcessRecord(pid=pid)
            return self._processes[pid]

    def register_process_start(
        self, pid: int, ppid: int, image_file_name: str, timestamp: datetime
    ) -> ProcessRecord:
        """Register a ProcessStart event."""
        with self._lock:
            proc = self.get_or_create(pid)
            proc.ppid = ppid
            proc.image_file_name = image_file_name or proc.image_file_name
            proc.start_time = timestamp
            proc.last_event_time = timestamp
            proc.status = ProcessStatus.ACTIVE

            # Link with parent process (handles out-of-order child arrival)
            if ppid > 0:
                self.get_or_create(ppid).children.add(pid)

            logger.debug(
                "Registered ProcessStart: PID=%d, PPID=%d, Image=%s",
                pid,
                ppid,
                proc.image_file_name,
            )
            return proc

    def register_process_stop(
        self, pid: int, timestamp: datetime, exit_code: int | None = None
    ) -> None:
        """Register a ProcessStop event."""
        with self._lock:
            proc = self._processes.get(pid)
            if proc:
                proc.stop_time = timestamp
                proc.exit_code = exit_code
                if proc.status != ProcessStatus.KILLED:
                    proc.status = ProcessStatus.STOPPED
                logger.debug(
                    "Registered ProcessStop: PID=%d, ExitCode=%s",
                    pid,
                    exit_code,
                )

    def add_event(self, pid: int, event: dict[str, Any]) -> None:
        """Add a syscall/ETW event to the process's event buffer."""
        with self._lock:
            proc = self.get_or_create(pid)

            # Try parsing timestamp to maintain timeline
            ts_str = event.get("Timestamp")
            if ts_str:
                with contextlib.suppress(Exception):
                    ts = parse_ts(ts_str)
                    proc.last_event_time = ts
                    if proc.start_time is None:
                        proc.start_time = ts

            if len(proc.events) < self._max_events_per_proc:
                proc.events.append(event)

    def hunt_process_tree(self, root_pid: int) -> tuple[set[int], list[dict[str, Any]]]:
        """Hunt a process and all its recursive descendants.

        Returns:
            all_pids: set of all PIDs belonging to this process subtree.
            all_events: chronological list of all events generated by the subtree.
        """
        with self._lock:
            all_pids: set[int] = set()
            queue = deque([root_pid])

            while queue:
                curr_pid = queue.popleft()
                if curr_pid in all_pids:
                    continue
                all_pids.add(curr_pid)

                proc = self._processes.get(curr_pid)
                if proc:
                    for child_pid in proc.children:
                        if child_pid not in all_pids:
                            queue.append(child_pid)

            # Collect events from all processes in the subtree
            combined_events: list[dict[str, Any]] = []
            for p in all_pids:
                record = self._processes.get(p)
                if record and record.events:
                    combined_events.extend(record.events)

            # Chronological sort
            def _sort_key(e: dict[str, Any]) -> float:
                try:
                    return parse_ts(e.get("Timestamp")).timestamp()
                except Exception:
                    return 0.0

            combined_events.sort(key=_sort_key)
            return all_pids, combined_events

    def get_candidate_roots_for_horizon(
        self, horizon: float, current_time: datetime
    ) -> list[ProcessRecord]:
        """Find active processes whose lifetime reached the horizon window.

        Args:
            horizon: window in seconds (e.g. 5.0)
            current_time: reference datetime

        Returns:
            List of ProcessRecord candidates eligible for feature extraction.
        """
        with self._lock:
            candidates: list[ProcessRecord] = []
            for proc in self._processes.values():
                if proc.start_time is None:
                    continue
                if proc.status in (ProcessStatus.MALICIOUS, ProcessStatus.KILLED):
                    continue
                if horizon in proc.evaluated_horizons:
                    continue

                age = (current_time - proc.start_time).total_seconds()
                if age >= horizon:
                    candidates.append(proc)

            return candidates

    def mark_evaluated(self, pid: int, horizon: float, is_malicious: bool) -> None:
        """Mark horizon as evaluated for process."""
        with self._lock:
            proc = self._processes.get(pid)
            if proc:
                proc.evaluated_horizons.add(horizon)
                if is_malicious:
                    proc.status = ProcessStatus.MALICIOUS
                elif proc.status == ProcessStatus.ACTIVE:
                    proc.status = ProcessStatus.EVALUATED_BENIGN

    def mark_killed(self, pids: set[int]) -> None:
        """Mark processes as terminated/killed."""
        with self._lock:
            for pid in pids:
                proc = self._processes.get(pid)
                if proc:
                    proc.status = ProcessStatus.KILLED
                    proc.stop_time = datetime.now()

    def cleanup_old_processes(self, max_age_seconds: float = 300.0) -> int:
        """Prune ancient terminated processes to bound memory usage."""
        now = datetime.now()
        with self._lock:
            to_remove = []
            for pid, proc in self._processes.items():
                if (
                    proc.status in (ProcessStatus.STOPPED, ProcessStatus.KILLED)
                    and proc.stop_time
                    and (now - proc.stop_time).total_seconds() > max_age_seconds
                ):
                    to_remove.append(pid)

            for pid in to_remove:
                del self._processes[pid]
            return len(to_remove)
